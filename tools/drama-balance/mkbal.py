# Assemble Source/Places/DramaBalance.inc from the calibration's lines (BAL, CLS, CAL, ELW, ARR).
import sys,re
src=open('/home/user/worldbuilder/Source/Places/Place.h').read()
m=re.search(r'placeKeys\s*\{([^}]*)\}',src)
keys=[k.strip().strip('"') for k in m.group(1).split(',') if k.strip()]
tab={};cls={};calm={};elw={};arrc={};arr2={};var={};dbl={};var80={}
for f in sys.argv[1:]:
    for line in open(f):
        p=line.split()
        if not p: continue
        if p[0]=='BAL': tab[(p[1],int(p[2]),int(p[3]))]=(float(p[4]),float(p[5]),float(p[6]) if len(p)>6 else 0.0)
        if p[0]=='CLS': cls[p[1]]=[float(x) for x in p[2:5]]
        if p[0]=='CAL': calm[p[1]]=float(p[3])-float(p[5])
        if p[0]=='ELW': elw[p[1]]=[float(x) for x in p[2:8]]
        if p[0]=='VAR': var[p[1]]=[float(x) for x in p[2:8]]
        if p[0]=='DBL': dbl[p[1]]=[float(x) for x in p[2:8]]
        if p[0]=='VAR80': var80[p[1]]=[float(x) for x in p[2:8]]
        if p[0]=='ARR': arrc[p[1]]=[float(x) for x in p[2:5]]
        if p[0]=='ARR2': arr2[p[1]]=[float(x) for x in p[2:5]]
out=["// Generated by the tests (WorldbuilderTests --only balancecal and arrcal; tools/drama-balance).",
"// Per Place: its Drama Styles (Driving, Epic, Tragic, Triumphant, Suspense) at Tension, Action",
"// and Climax, { the Place's balance (0 since the orchestration pass: the Place never makes",
"// room), the Drama layer's, its percussion against the layer } (dB); its Classic loudness at Score Intensity 62, 80 and 100 %",
"// against 50 % (dB); at 35 % against 50 %; its six instruments alone against the whole Place",
"// (dB); in an arrangement, Tension, Action and Climax against the engine's estimate (dB), alone",
"// and in a further slot (the loudness pass's section balance); its six instruments' busier",
"// variant B against A at 100 %, doubled at a climax against not, B against A at 80 % (dB).",
"const std::array<BalanceRow, PlaceTypeCount> balanceTable { {"]
f2=lambda v:"%.2ff"%v
for i,k in enumerate(keys):
    rows=["{ { "+", ".join("{ %.1ff, %.1ff, %.1ff }"%tab.get((k,s,t),(0.0,0.0,0.0)) for t in (1,2,3))+" } }" for s in range(1,6)]
    c=cls.get(k,[0.0]*3); w=elw.get(k,[0.0]*6); a=arrc.get(k,[0.0]*3)
    out.append("    { { { "+", ".join(rows)+" } }, { "+", ".join(map(f2,c))+" }, "+f2(calm.get(k,0.0))+", { "+", ".join("%.1ff"%x for x in w)+" }, { "+", ".join(map(f2,a))+" }, { "+", ".join(map(f2,arr2.get(k,[0.0]*3)))+" }, { "+", ".join("%.1ff"%x for x in var.get(k,[0.0]*6))+" }, { "+", ".join("%.1ff"%x for x in dbl.get(k,[0.0]*6))+" }, { "+", ".join("%.1ff"%x for x in var80.get(k,[0.0]*6))+" } },   // "+(k if i else "none"))
out.append("} };")
open('/home/user/worldbuilder/Source/Places/DramaBalance.inc','w').write("\n".join(out)+"\n")
print(len(tab),"BAL",len(cls),"CLS",len(calm),"CAL",len(elw),"ELW",len(arrc),"ARR")

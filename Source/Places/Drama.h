#pragma once
// The Drama tier (after the performance pass): a game score's vertical layering on top
// of every Place. Score Intensity (and, near its top, the Place's Tension) moves the
// world through four tiers: Calm -> Tension -> Action -> Climax. Calm is the Place as it
// always was. From Tension on, a Drama layer joins the Place and changes gear on the bar
// lines: a pedal-point pulse and distant drums at Tension; at Action a driving ostinato,
// war drums and stabs on the downbeats; at Climax double-time drums, toms, cymbal swells,
// choir and brass stabs, low piano strikes and impacts on the phrase lines.
//
// Architecture (DEVLOG, "Drama tier" and its rework): each Place slot has three Drama
// instruments (elements 6-8: drums, ostinato, hits), themed by the Place it plays (a
// table: which drums, which ostinato, which hits). They are real instruments: patterns
// (generated by the tier, the style and the Place, then editable, with variants), ARRANGE
// rows, KEYS, levels, switches, mute / solo and effects, host parameters appended after
// every older one. A session or scene that does not ask for drama (Drama 0: projects from
// before it, the older factory scenes) never builds or renders them, so it sounds exactly
// as before and costs nothing. The layer renders only while a tier above Calm plays (and
// its tails ring), or the keyboard plays one of them.
//
// The arrangement uses it: a section can set its tier (or follow its Score Intensity),
// and the transitions get their dramatic sounds (a drum roll and a cymbal swell into a
// Riser or a Drum fill, impacts and stabs landing on the downbeat after Riser, Drum fill
// and Drop). The shared harmonic clock changes gear with the world's tier (music.h).
//
// Nothing here allocates after prepare().
#include "Places.h"
#include "../DSP/Master.h"

namespace wb::drama {

enum Tier { Calm, Tension, Action, Climax, TierCount };
inline constexpr std::array<const char*, TierCount> tierNames { "Calm", "Tension", "Action", "Climax" };

// The feel of the drama (the Drama Style parameter; Auto: the Place's own).
enum Style { StyleAuto, StyleDriving, StyleEpic, StyleTragic, StyleTriumphant, StyleSuspense, StyleCount };
inline constexpr const char* styleChoices = "Auto|Driving|Epic|Tragic|Triumphant|Suspense";

// The drama amount x (0..1) of a slot: how far above the middle Score Intensity is; the
// Place's own Tension (with Danger) pushes it further once Intensity is above the middle.
// Below or at the middle nothing changes at all.
inline float amountFor(float intensity, float tension, float drama) {
    const float above = std::clamp(2.0f * (intensity - 0.5f), 0.0f, 1.0f);
    const float push = 1.0f + 0.6f * std::max(0.0f, std::clamp(tension, 0.0f, 1.0f) - 0.5f);
    return std::clamp(drama, 0.0f, 1.0f) * std::clamp(above * push, 0.0f, 1.0f);
}
inline int tierFor(float x) { return x < 0.1f ? Calm : (x < 0.45f ? Tension : (x < 0.78f ? Action : Climax)); }

// What a slot's Drama layer is told each chunk (from the engine and the arrangement).
struct Cue {
    float drama = 0;          // the Drama parameter (0: Classic, no layer at all)
    int style = StyleAuto;
    int tier = -1;            // the arrangement section's tier (-1: from Score Intensity)
    // The Drama tier rework: the section's gear as the arrangement shapes it (0 Calm .. 3
    // Climax, continuous; < 0: none, the tier above or Score Intensity decides).
    float gear = -1;
    float heat = -1;          // an evolving section's progress (harder as it rises; < 0: none)
    int rank = 0;             // the slot's place among the active slots (0 leads: drums)
    // The arrangement's transition under way and the one that led into this section.
    uint8_t transition = 0, arrived = 0;
    float transitionT = -1;
    double transitionLength = 0, sinceStart = 1.0e9;
    bool drumFill = false;
};

// Each Place's dramatic colour.
enum Kit { KitWar, KitTribal, KitMetal, KitHybrid, KitMarch };
enum Ostinato { OstStrings, OstPulse, OstBass, OstPluck, OstPiano };
enum Hit { HitBrass, HitChoir, HitPiano, HitBraam, HitSynth, HitMetal };
struct Theme {
    int kit = KitWar, ostinato = OstStrings, hitA = HitBrass, hitB = HitChoir, style = StyleDriving;
    float drumSemis = -7;     // the djembes pitched down (war drums) or up
    float hall = 0.6f;        // the layer's own space
    const char* text = "";
};
const Theme& theme(int placeType);
// The style that plays for a Place with the Drama Style parameter at `style`.
inline int styleFor(int placeType, int style) { return style > StyleAuto && style < StyleCount ? style : theme(placeType).style; }

// The Drama loudness pass: drama makes the music more intense, not louder. At each tier
// the Place makes room (placeDb, applied to the whole slot) and the Drama layer plays at
// its share of the Calm level (layerDb, its level in the slot as the tier set it), so
// Calm, Tension, Action and Climax are about equally loud. Measured per Place, Drama Style
// and tier at the tier's probe point (Score Intensity 62, 80, 100 %; Tests "balancecal",
// DramaBalance.inc); between them the Place's own rise with Score Intensity (its Classic
// loudness curve, measured too) is balanced as well, so a tier stays level whatever
// Intensity is. Calm: 0, 0.
struct Balance {
    float placeDb = 0, layerDb = 0;
};
Balance balance(int placeType, int style, int tier, int rank, float intensity = -1.0f);
// The Place's Classic loudness at Score Intensity `intensity` (dB against 50 %, measured;
// below 50 % through its Calm level at 35 %), and the level its tiers are balanced to.
float classicRiseDb(int placeType, float intensity);
float balancedDb(int placeType);
// One of the Place's six instruments alone against the whole Place (dB, measured).
float elementWeightDb(int placeType, int element);
// In an arrangement, a section above Calm against the engine's estimate of it (dB, measured).
float arrangedCorrectionDb(int placeType, int tier, int rank = 0);
// The Drama layer's share of a slot's loudness at Tension, Action and Climax (the balance).
inline constexpr std::array<float, 3> layerShare { 0.35f, 0.5f, 0.55f };
// A Drama layer's power on the second and further Places against the leading one's.
inline float rankLayerPower(int rank) { return rank <= 0 ? 1.0f : (rank == 1 ? 0.25f : 0.1f); }
// Tests only: the balance off (the probe measures the Place and the layer as they were).
inline bool balanceOff = false;
// Tests only: false plays the Drama tier as it was before the loudness pass (the old hit
// levels, no balance, no layer limiter): the "before" of the listening renders.
inline bool loudnessPass = true;

// The Drama instruments' kit rows (the Drama tier rework). The drums: the low (war) drum,
// the mid drum, a third voice that depends on the kit (slaps and their muted ghosts; a
// clank; a hat; snare ghost strokes), the snare (a clap on a hybrid kit), two toms, and
// the pistons of a metal kit. The hits: the Place's two stabs (chords on the current
// chord), an impact with a crash, and a cymbal swell as long as its note.
enum DrumLine { RowLow, RowMid, RowHigh, RowSnare, RowTomHigh, RowTomLow, RowPistons, DrumRowCount };
enum HitRow { RowStabA, RowStabB, RowImpact, RowSwell, HitRowCount };

// Writes the starting pattern of a Drama instrument (`element`: DramaDrums, DramaOstinato
// or DramaHits) for a Place: the tier in.tier (Tension .. Climax), the style in.style, the
// slot's rank in.rank (the leading slot plays the drums and the impacts, the second the
// ostinato too), the Mood, in.tension (a semitone's rub at the top) and the variant: A the
// tier's own bars, B busier (the next tier's), C sparser (the one below), the Fill a bar
// that drives into the next section. in.variant (Generate) makes another take. A pure
// function of its inputs.
void generate(int placeType, int element, int variant, const GenInputs& in, pat::Pattern& out);

// The Drama layer of one slot: its three Drama instruments as they play.
class Layer {
public:
    Layer();
    void prepare(float sampleRate);
    void reset();
    void setSeed(uint32_t key);

    // The tier for the chunk [beat, beat + span): latched on the bar lines (a jump in
    // Score Intensity changes gear on the next one). Called before the patterns are
    // chosen, so a new tier's patterns start on its first downbeat. Returns the tier.
    int advance(int placeType, const WorldFrame& world, const Cue& cue, float tension, double beat, double span);
    // The tier the patterns are written for now (Tension at least: what the Pattern
    // Editor shows while the drama rests).
    int patternTier() const { return std::max(int(Tension), latched); }

    // What the slot's three Drama instruments play this chunk.
    struct Elements {
        std::array<const pat::Playback*, dramaElements> play {};   // nullptr: no pattern
        std::array<float, dramaElements> gainFrom {}, gainTo {};   // level, switch, mute and arrangement (per chunk, ramped)
        std::array<bool, dramaElements> notes {};                  // may start new notes
        dsp::InstrumentFx* fx = nullptr;                           // the slot's instrument effects (elements 6-8)
        float fxDepth = 1;
        // KEYS and Instrument mode: the Drama instrument the keyboard plays (0-2, -1: none)
        // and its live notes; `instrument`: Instrument mode (only the live notes, close).
        int liveElement = -1;
        const keys::Live* live = nullptr;
        bool instrument = false;
        // The slot's balance gain after the layer (the Drama loudness pass): the limiter's
        // ceiling holds at the level the layer is heard at.
        float slotGain = 1;
    };
    // Adds the layer to left/right (n <= dsp::chunk). Returns false (adding nothing)
    // while it is silent.
    bool render(int placeType, const WorldFrame& world, const Cue& cue, float tension, double beat, double beatsPerSample, bool sync,
                const Elements& elements, uint64_t clock, float* left, float* right, int n);
    // The tier playing now (latched on the bar lines) and the drama amount.
    int tier() const { return latched; }
    // The tier it will latch on the next bar line (the Drama loudness pass: the Place makes
    // room for it at once, as Score Intensity's own rise arrives at once).
    int wanted() const { return want; }
    float amount() const { return x; }
    // Notes started since prepare() (for the tests: rhythmic density).
    uint32_t started() const { return startedCount; }
    bool active() const { return awake; }
    // The layer's look-ahead limiter (the Drama loudness pass): how much it has turned the
    // layer down (it should rarely engage), and a clear for the tests.
    const dsp::Reduction& reduction() const { return limiter.reduction; }
    void clearReduction() { limiter.reduction.clear(); }
    // The layer's own peak since the last clear (after its limiter, before its hall).
    float busPeak() const { return peakOut; }
    void clearPeak() { peakOut = 0; }
    // The part a Drama instrument's live notes sound on (its own transposition).
    float transposeSemis(int element) const;
    // Every note the three Drama instruments' patterns played, for the tests: the sample,
    // the instrument (6-8), its row (kit) or degree, and its velocity.
    struct Logged {
        uint64_t clock = 0;
        int element = -1, row = 0;
        float velocity = 0;
    };
    static constexpr int logSize = 1024;
    uint32_t loggedCount() const { return logged; }
    const Logged& loggedAt(uint32_t i) const { return eventLog[std::size_t(i % logSize)]; }

    enum PartId {
        PDrums, PPerc, PMetal, PSwell, PStrings, PPulse, PBass, PPluck, PLow, PBrass, PChoir, PPiano, PBraam, PSynth, PHands,
        // The Drama tier rework: the doublings and hits on parts of their own, so each Drama
        // instrument has its own bus (its level and effects).
        PBrassOst, PPianoOst, PMetalHit, PImpact, PartCount
    };
    // Which Drama instrument (0 drums, 1 ostinato, 2 hits) a part belongs to.
    static int elementOf(int part);

private:
    struct Note {
        int offset = 0, part = 0;
        int stop = 0;   // a live note's key released (its id), not a new note
        NoteOn on;
    };
    static constexpr int maxNotes = 160;
    void configure(int placeType, const WorldFrame& world, int style, float tension, float bpm);
    // The arrangement's and the gear changes' own sounds (stingers, rolls into a section,
    // its landing), at the step `step` (sixteenths).
    void stingers(int64_t step, int offset, int placeType, int style, const WorldFrame& world, bool sync, double stepBeat, const Cue& cue,
                  const Elements& el);
    void playDrum(int row, int offset, float velocity, double beat, double length, int kit, int live = 0);
    void playOstinato(int offset, float semis, float velocity, double beat, double length, bool accent, bool onBeat, const Elements& el, int live = 0);
    void playHit(int row, int offset, float velocity, double beat, double length, int placeType, const WorldFrame& world, int chord, int64_t bar,
                 float tension, int live = 0);
    void add(int part, int offset, float semis, float velocity, double beat, double lengthBeats, int row = 0, float pan = 2.0f, int live = 0);
    void chord(int part, int offset, int root, int mood, int chordDegree, float velocity, double beat, double length, bool power, int colour = 0);
    float rand(int64_t step, uint32_t salt) const;

    float rate = 48000;
    uint32_t seedKey = 0;
    dsp::Stream noise;
    // Fallbacks (the synthesised parts that play when the bank has no recordings).
    DrumPart drumsSynth, handsSynth, perc, metal, metalHit, impact;
    NoisePart swell;
    BowedPart stringsSynth;
    SynthPart pulseSynth, bassSynth, low, brass, brassOst, pianoSynth, pianoOstSynth, braamSynth, synthStabSynth;
    PluckPart pluckSynth;
    ChoirPart choirSynth;
    // The war drums (the low and mid strokes) and the hands (slaps and ghost notes) apart,
    // so the dense hand strokes never cut the booms short.
    HitPart drums { drumsSynth }, hands { handsSynth };
    SamplePart strings { stringsSynth }, pulse { pulseSynth }, bass { bassSynth }, pluck { pluckSynth }, piano { pianoSynth }, pianoOst { pianoOstSynth },
        braam { braamSynth }, synthStab { synthStabSynth };
    VoicePart choir { choirSynth, &choirSynth };
    std::array<Part*, PartCount> parts {};
    std::array<float, PartCount> gainNow {};
    std::array<int, PartCount> quiet {};   // samples since the part's last note
    std::array<Note, maxNotes> pending {};
    int count = 0;
    PartFrame frame;
    std::array<float, dsp::chunk> busL {}, busR {}, partL {}, partR {};
    std::array<std::array<float, dsp::chunk>, dramaElements> elemL {}, elemR {};
    dsp::SmallSpace hall;
    // A transparent look-ahead limiter on the layer's sum (1.5 ms): stacked hits on one
    // downbeat never reach past its ceiling, and it rarely engages (Tests "loudness").
    dsp::LookaheadLimiter limiter;
    static constexpr float limiterCeiling = 0.708f;   // -3 dBFS at the balanced level, before the slot's level and pan
    float peakOut = 0;
    float hallWet = 0.5f;
    dsp::Smoother level;
    int type = -1;
    int latched = Calm, previous = Calm, want = Calm;
    float x = 0;
    bool awake = false, fresh = true, gearChange = false;
    int64_t lastBar = INT64_MIN, gearBar = INT64_MIN;
    int idleSamples = 0;
    uint32_t startedCount = 0, logged = 0;
    std::array<Logged, logSize> eventLog {};
    double lastBeat = -1.0e18;
    float heat = 0;   // x within its tier, for velocities
    uint64_t patchKey = 0;   // what the patches were last set for
    int kitNow = KitWar, ostinatoPart = PStrings;
    float ostinatoRegister = 0;
    // While a chunk's notes are made: the live note they belong to, a drum ghost stroke,
    // the slot's rank and the ostinato's chord root.
    int liveId = 0, rankNow = 0, rootNow = 0;
    bool ghost = false;
    static constexpr float layerTrimDb = 0.0f;   // the layer's level against its Place (Tests "drama")
public:
    // Tests only (the balance probe): the parts that sound (a bit per PartId).
    static inline uint32_t partMask = 0xffffffffu;
};

} // namespace wb::drama
